import { createHash } from 'node:crypto';
import { readFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
export const SPEECH_ROOT = fileURLToPath(new URL('../', import.meta.url));
export const SPEECH_ASSETS = 'src/wasm/speech';
export const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
export async function speechInputs(root = SPEECH_ROOT) {
    const files = ['scripts/speech-assets.mjs','scripts/build-speech.mjs'];
    async function visit(relative) {
        for(const entry of await readdir(join(root,relative),{withFileTypes:true})) {
            if(['target','.DS_Store'].includes(entry.name)) continue;
            const path=`${relative}/${entry.name}`;
            if(entry.isDirectory()) await visit(path); else files.push(path);
        }
    }
    await visit('wasm/speech-planner'); await visit('wasm/airway/vendor/chimera');
    files.push('wasm/airway/Cargo.toml','wasm/airway/source-lock.json');
    const inputs=await Promise.all(files.sort().map(async path=>({path,sha256:sha256(await readFile(join(root,path)))})));
    return {inputs,version:sha256(JSON.stringify(inputs))};
}
export function speechManifest(m) {
    // The same manifest supplies the default plan in AudioWorklet, where URL is
    // not a global. Resolve sibling URLs with ECMAScript string operations.
    return `// Generated by npm run build:speech. Planner loads only when editing.\nexport { DEFAULT_SPEECH } from './${m.phraseFile}';\nconst base = import.meta.url.slice(0, import.meta.url.lastIndexOf('/') + 1);\nexport const SPEECH_PLANNER = Object.freeze({version:'${m.version}',moduleUrl:base+'${m.moduleFile}',dictionaryUrl:base+'${m.dictionaryFile}'});\n`;
}
export async function validateSpeechAssets({root=SPEECH_ROOT}={}) {
    const dir=join(root,SPEECH_ASSETS);
    let m; try { m=JSON.parse(await readFile(join(dir,'artifact-manifest.json'),'utf8')); }
    catch { throw new Error('Missing speech assets. Run npm run build:speech.'); }
    const source=await speechInputs(root);
    if(m.schemaVersion!==1 || m.version!==source.version || JSON.stringify(m.inputs)!==JSON.stringify(source.inputs)) throw new Error('Stale speech assets. Run npm run build:speech.');
    const expected=[m.moduleFile,m.wasmFile,m.dictionaryFile,m.phraseFile,'LICENSES.txt'];
    if(!Array.isArray(m.files) || m.files.length!==5 || new Set(expected).size!==5 ||
        !/^speech-[a-f0-9]{64}\.js$/.test(m.moduleFile) || !/^speech-[a-f0-9]{64}\.wasm$/.test(m.wasmFile) ||
        !/^cmudict-[a-f0-9]{64}\.gz$/.test(m.dictionaryFile) || !/^speech-default-[a-f0-9]{64}\.js$/.test(m.phraseFile)) throw new Error('Invalid speech asset manifest.');
    for(const f of m.files) {
        if(!expected.includes(f.name)) throw new Error('Unexpected speech artifact.');
        const data=await readFile(join(dir,f.name)), hash=sha256(data);
        if(f.bytes!==data.byteLength || f.sha256!==hash || (f.name!=='LICENSES.txt' && !f.name.includes(hash))) throw new Error(`Invalid speech checksum: ${f.name}`);
    }
    if(await readFile(join(dir,'manifest.js'),'utf8')!==speechManifest(m)) throw new Error('Invalid speech loader.');
    return m;
}
