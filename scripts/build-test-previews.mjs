import { createHash } from 'node:crypto';
import { mkdir, readdir, unlink, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import sharp from 'sharp';
import { TEST_PATCHES } from '../src/js/config/test-patches.js';
import { getThumbnailCacheKey, PATCH_PREVIEW_RENDERER_VERSION, PATCH_THUMBNAIL_OPTIONS } from '../src/js/patches/patch-preview.js';

// Run npm run build and a local dev server first. The renderer is the same
// rack-only DOM/canvas capture used by saved patches; no audio engine starts.
const origin = process.argv[2] || 'http://127.0.0.1:4176';
const target = new URL('../src/patch-previews/', import.meta.url);
await mkdir(target, { recursive: true });
const browser = await chromium.launch({ headless: true });
const records = Object.entries(TEST_PATCHES);
const completed = new Map();
const measurements = [];
let next = 0;
try {
    await Promise.all(Array.from({ length: 3 }, async () => {
        const page = await browser.newPage();
        await page.goto(new URL('/patch-preview.html', origin).href);
        await page.waitForFunction(() => window.eurorackPatchPreview);
        while (next < records.length) {
            const [name, patch] = records[next++];
            const result = await page.evaluate(async ({ state, options }) => {
                const started = performance.now();
                const blob = await window.eurorackPatchPreview.capture(state, options);
                const data = await new Promise((resolve, reject) => {
                    const reader = new FileReader(); reader.onload = () => resolve(reader.result); reader.onerror = reject; reader.readAsDataURL(blob);
                });
                return { data, captureMs: Math.round(performance.now() - started) };
            }, { state: patch.state, options: PATCH_THUMBNAIL_OPTIONS });
            const png = Buffer.from(result.data.split(',')[1], 'base64');
            const webp = await sharp(png).webp({ quality: 82, effort: 6, smartSubsample: true }).toBuffer();
            const { width, height } = await sharp(webp).metadata();
            const file = `${createHash('sha256').update(webp).digest('hex')}.webp`;
            await writeFile(new URL(file, target), webp);
            completed.set(name, { key: await getThumbnailCacheKey(patch.state), rendererVersion: PATCH_PREVIEW_RENDERER_VERSION, file, width, height, bytes: webp.length });
            measurements.push({ name, width, height, pngBytes: png.length, webpBytes: webp.length, captureMs: result.captureMs });
            if (completed.size % 10 === 0 || completed.size === records.length) console.log(`Rendered ${completed.size}/${records.length} test previews`);
        }
        await page.close();
    }));
} finally { await browser.close(); }
const manifest = Object.fromEntries(records.map(([name]) => [name, completed.get(name)]));
await writeFile(new URL('../src/js/config/test-patch-previews.js', import.meta.url), `// Generated by scripts/build-test-previews.mjs. Never hand-edit image paths.\nexport const TEST_PATCH_PREVIEWS = ${JSON.stringify(manifest, null, 2)};\n`);
const used = new Set([...completed.values()].map(item => item.file));
for (const file of await readdir(target)) if (/^[a-f0-9]{64}\.webp$/.test(file) && !used.has(file)) await unlink(new URL(file, target));
const total = field => measurements.reduce((sum, item) => sum + item[field], 0);
const sorted = field => measurements.map(item => item[field]).sort((a, b) => a - b);
const stats = field => { const values = sorted(field); return { min: values[0], median: values[Math.floor(values.length / 2)], max: values.at(-1), total: total(field) }; };
console.log(JSON.stringify({ count: measurements.length, dimensions: PATCH_THUMBNAIL_OPTIONS, png: stats('pngBytes'), webp: stats('webpBytes'), captureMs: stats('captureMs'), output: fileURLToPath(target) }, null, 2));
