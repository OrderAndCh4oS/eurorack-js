import { createHash } from 'node:crypto';
import { readFile, readdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const AUDIO_ANALYSIS_ROOT = fileURLToPath(new URL('../', import.meta.url));
export const AUDIO_ANALYSIS_ASSETS = 'src/wasm/audio-analysis';
export const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

export async function audioAnalysisInputs(root = AUDIO_ANALYSIS_ROOT) {
    const files = ['scripts/audio-analysis-assets.mjs', 'scripts/build-audio-analysis.mjs', 'scripts/audio-analysis-licenses/dasp-0.11.0-MIT.txt'];
    async function visit(relative) {
        for (const entry of await readdir(join(root, relative), {withFileTypes: true})) {
            if (['target', '.git', 'tests', 'benches', 'examples'].includes(entry.name)) continue;
            const path = `${relative}/${entry.name}`;
            if (entry.isDirectory()) await visit(path);
            else if (entry.name.endsWith('.rs') || ['Cargo.toml', 'Cargo.lock', 'rust-toolchain.toml', 'config.toml'].includes(entry.name)) files.push(path);
        }
    }
    await visit('wasm/audio-analysis');
    if (!files.includes('wasm/audio-analysis/Cargo.lock')) throw new Error('Missing audio analysis Cargo.lock. Run npm run build:audio-analysis.');
    const inputs = await Promise.all(files.sort().map(async path => ({path, sha256: sha256(await readFile(join(root, path)))})));
    return {inputs, version: sha256(JSON.stringify(inputs))};
}

export function audioAnalysisModuleManifest(version, moduleFile) {
    return `// Generated by npm run build:audio-analysis. Loaded only on demand.\nexport const AUDIO_ANALYSIS = Object.freeze({\n    version: ${JSON.stringify(version)},\n    moduleUrl: new URL(${JSON.stringify(`./${moduleFile}`)}, import.meta.url).href\n});\n`;
}

/** Verify committed outputs without Rust, Cargo, wasm-bindgen or network access. */
export async function validateAudioAnalysisAssets({root = AUDIO_ANALYSIS_ROOT} = {}) {
    const assets = resolve(root, AUDIO_ANALYSIS_ASSETS);
    let manifest;
    try { manifest = JSON.parse(await readFile(join(assets, 'artifact-manifest.json'), 'utf8')); }
    catch { throw new Error('Missing audio analysis assets. Run npm run build:audio-analysis and commit the generated files.'); }
    const source = await audioAnalysisInputs(root);
    if (manifest.schemaVersion !== 1 || manifest.version !== source.version || JSON.stringify(manifest.inputs) !== JSON.stringify(source.inputs)) {
        throw new Error('Stale audio analysis assets. Run npm run build:audio-analysis and commit the generated files.');
    }
    if (!Array.isArray(manifest.files) || manifest.files.length !== 3) throw new Error('Invalid audio analysis artifact manifest.');
    const names = new Set(manifest.files.map(file => file.name));
    if (names.size !== 3 || !names.has('LICENSES.txt') || !names.has(manifest.moduleFile) || !names.has(manifest.wasmFile)) throw new Error('Invalid audio analysis artifact list.');
    if (!/^audio-analysis-[a-f0-9]{64}\.js$/.test(manifest.moduleFile) || !/^audio-analysis-[a-f0-9]{64}\.wasm$/.test(manifest.wasmFile)) throw new Error('Invalid audio analysis artifact names.');
    for (const file of manifest.files) {
        const bytes = await readFile(join(assets, file.name));
        const digest = sha256(bytes);
        if (bytes.byteLength !== file.bytes || digest !== file.sha256 || (file.name !== 'LICENSES.txt' && !file.name.includes(digest))) {
            throw new Error(`Audio analysis artifact checksum mismatch: ${file.name}`);
        }
        if (file.name === manifest.wasmFile && !WebAssembly.Module.exports(new WebAssembly.Module(bytes)).some(item => item.name === 'analyze' && item.kind === 'function')) {
            throw new Error('Audio analysis WASM is missing its analyze export.');
        }
    }
    const jsManifest = await readFile(join(assets, 'manifest.js'), 'utf8');
    if (jsManifest !== audioAnalysisModuleManifest(source.version, manifest.moduleFile)) throw new Error('Audio analysis loader manifest mismatch.');
    const moduleSource = await readFile(join(assets, manifest.moduleFile), 'utf8');
    if (!moduleSource.includes(manifest.wasmFile)) throw new Error('Audio analysis module does not reference its WASM asset.');
    return manifest;
}
