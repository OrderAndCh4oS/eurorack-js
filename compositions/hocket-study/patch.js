// Hocket Study — two plucked voices sharing a seven-note phrase.
// Replace HOCKET_TYPE with the immutable local type returned by describe_modules.
// CLK runs at 3.2 events/second (eighth notes at 96 BPM).
patch()
  .module('clk', 'clock', { rate: Math.log10(32) / 5 }, { row: 1, index: 0 })
  .module('seq', 'phrase', {
    step1: 5/12, step2: 0, step3: 3/12, step4: 7/12,
    step5: 10/12, step6: 1, step7: 7/12,
    length: 7, range: 0, direction: 0
  }, { row: 1, index: 1 })
  .module('HOCKET_TYPE', 'router', { pattern: 2, rotate: 0, swap: 0 }, { row: 1, index: 2 })
  .module('sh', 'heldNotes', { slew1: 0, slew2: 0 }, { row: 1, index: 3 })
  .module('pluck', 'low', { pitch: 0.25, decay: 0.55, damp: 0.48, position: 0.24 }, { row: 1, index: 4 })
  .module('pluck', 'high', { pitch: 0.45, decay: 0.67, damp: 0.68, position: 0.33 }, { row: 1, index: 5 })
  .module('lfo', 'motion', { rateKnob: 0.16, waveKnob: 0 }, { row: 1, index: 6 })
  .module('atten', 'depth', { atten1: 0.59, offset1: 0.455, atten2: 0.43, offset2: 0.535 }, { row: 1, index: 7 })
  .module('mix', 'left', { lvl1: 0.72, lvl2: 0.24, lvl3: 0, lvl4: 0 }, { row: 1, index: 8 })
  .module('mix', 'right', { lvl1: 0.27, lvl2: 0.66, lvl3: 0, lvl4: 0 }, { row: 1, index: 9 })
  .module('verb', 'room', { time: 0.61, damp: 0.65, mix: 0.25 }, { row: 1, index: 10 })
  .module('db', 'meter', { mode: 2, hold: 1 }, { row: 1, index: 11 })
  .module('out', 'main', { volume: 0.65 }, { row: 1, index: 12 })
  .connect('clock.clock', 'phrase.clock')
  .connect('clock.clock', 'router.clock')
  .connect('phrase.cv', 'heldNotes.in1')
  .connect('phrase.cv', 'heldNotes.in2')
  .connect('router.a', 'heldNotes.trig1')
  .connect('router.b', 'heldNotes.trig2')
  .connect('heldNotes.out1', 'low.vOct')
  .connect('heldNotes.out2', 'high.vOct')
  .connect('router.a', 'low.trigger')
  .connect('router.b', 'high.trigger')
  .connect('motion.primary', 'depth.in1')
  .connect('motion.primary', 'depth.in2')
  .connect('depth.out1', 'low.positionCV')
  .connect('depth.out2', 'high.positionCV')
  .connect('low.out', 'left.in1')
  .connect('high.out', 'left.in2')
  .connect('low.out', 'right.in1')
  .connect('high.out', 'right.in2')
  .connect('left.out', 'room.audioL')
  .connect('right.out', 'room.audioR')
  .connect('room.outL', 'meter.L')
  .connect('room.outR', 'meter.R')
  .connect('meter.outL', 'main.L')
  .connect('meter.outR', 'main.R')
