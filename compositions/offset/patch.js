// Offset — two interlocking plucked sequences and a centred bass, 112 BPM.
// SEQ range 0 is one octave; each semitone is 1/12 V.
const upper = [0, 7, 10, 3, 5];
const lower = [12, 10, 7, 5, 3, 7, 10, 5];
const roots = [0, 0, 5, 10];
const steps = notes => Object.fromEntries(notes.map((note, i) => [`step${i + 1}`, note / 12]));

patch()
  .module('clk', 'clock', {rate: 0.31441935359}, {row: 1, index: 0})
  .module('div', 'divide', {rate1: 0.4375, rate2: 0.3125}, {row: 1, index: 1})
  .module('seq', 'upper', {...steps(upper), length: 5, range: 0}, {row: 1, index: 2})
  .module('seq', 'lower', {...steps(lower), length: 8, range: 0, gate2: 0, gate4: 0, gate6: 0, gate7: 0}, {row: 1, index: 3})
  .module('pluck', 'lead', {pitch: 0.483333333333, decay: 0.57, damp: 0.68, position: 0.28}, {row: 1, index: 4})
  .module('pluck', 'answer', {pitch: 0.283333333333, decay: 0.64, damp: 0.58, position: 0.44}, {row: 1, index: 5})
  .module('chorus', 'width', {rate: 0.07, depth: 0.16, mix: 0.18}, {row: 1, index: 6})
  .module('verb', 'room', {time: 0.56, damp: 0.62, mix: 0.23}, {row: 1, index: 7})
  .module('out', 'main', {volume: 1}, {row: 1, index: 8})
  .module('seq', 'roots', {...steps(roots), length: 4, range: 0}, {row: 2, index: 0})
  .module('vco', 'bass', {coarse: 0.33225629758, fine: 0, glide: 18}, {row: 2, index: 1})
  .module('vcf', 'tone', {cutoff: 0.34, resonance: 0.19}, {row: 2, index: 2})
  .module('func', 'shape', {rise: 0.21, fall: 0.71, curve: 0.38, cycle: 0}, {row: 2, index: 3})
  .module('vca', 'bassAmp', {ch1Gain: 0.4, ch2Gain: 0}, {row: 2, index: 4})
  .module('lfo', 'motion', {rateKnob: 0.12, waveKnob: 0}, {row: 2, index: 5})
  .module('atten', 'mod', {atten1: 0.58, offset1: 0.5, atten2: 0.75, offset2: 0.5}, {row: 2, index: 6})
  .module('mix', 'left', {lvl1: 0.65, lvl2: 0.4, lvl3: 0.35, lvl4: 0}, {row: 2, index: 7})
  .module('mix', 'right', {lvl1: 0.85, lvl2: 0.4, lvl3: 0.9, lvl4: 0}, {row: 2, index: 8})
  .connect('clock.clock', 'divide.clock')
  .connect('clock.clock', 'upper.clock')
  .connect('divide.out1', 'lower.clock')
  .connect('divide.out2', 'roots.clock')
  .connect('upper.cv', 'lead.vOct')
  .connect('upper.gate', 'lead.trigger')
  .connect('lower.cv', 'answer.vOct')
  .connect('lower.gate', 'answer.trigger')
  .connect('roots.cv', 'bass.vOct')
  .connect('roots.gate', 'shape.trig')
  .connect('bass.ramp', 'tone.audio')
  .connect('tone.lpf', 'bassAmp.ch1In')
  .connect('shape.out', 'mod.in2')
  .connect('mod.out2', 'bassAmp.ch1CV')
  .connect('mod.out2', 'tone.cutoffCV')
  .connect('motion.primary', 'mod.in1')
  .connect('mod.out1', 'lead.dampCV')
  .connect('mod.out1', 'answer.positionCV')
  .connect('lead.out', 'width.inL')
  .connect('answer.out', 'width.inR')
  .connect('width.outL', 'room.audioL')
  .connect('width.outR', 'room.audioR')
  .connect('room.outL', 'left.in1')
  .connect('room.outR', 'right.in1')
  .connect('lead.out', 'left.in3')
  .connect('answer.out', 'right.in3')
  .connect('bassAmp.ch1Out', 'left.in2')
  .connect('bassAmp.ch1Out', 'right.in2')
  .connect('left.out', 'main.L')
  .connect('right.out', 'main.R')
