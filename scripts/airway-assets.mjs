import { createHash } from 'node:crypto';
import { readFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const AIRWAY_ROOT = fileURLToPath(new URL('../', import.meta.url));
export const AIRWAY_ASSETS = 'src/wasm/airway';
export const AIRWAY_COMMIT = '24bd2e4ee4accf7b27d57d8bf912472880dff9f7';
export const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

/** Reject state outside linear memory that a snapshot would fail to restore. */
export function inspectAirwayAbi(bytes) {
    let offset = 8;
    const uint = () => {
        let value = 0, shift = 0, byte;
        do { byte = bytes[offset++]; value += (byte & 127) * 2 ** shift; shift += 7; } while (byte & 128);
        return value;
    };
    const name = () => { const length = uint(); const value = Buffer.from(bytes.subarray(offset, offset + length)).toString('utf8'); offset += length; return value; };
    const mutableGlobals = [];
    const globalExports = new Map();
    let memoryBytes = 0;
    while (offset < bytes.length) {
        const section = bytes[offset++];
        const length = uint();
        const end = offset + length;
        if (section === 5) {
            if (uint() !== 1 || uint() !== 1) throw new Error('Airway requires one unshared memory with explicit maximum.');
            const min = uint(), max = uint();
            if (min !== max || min > 16) throw new Error('Airway memory must have equal initial/maximum size, at most 1 MiB.');
            memoryBytes = min * 65536;
        } else if (section === 6) {
            const count = uint();
            for (let index = 0; index < count; index++) {
                const type = bytes[offset++], mutable = bytes[offset++];
                if (type !== 0x7f || bytes[offset++] !== 0x41) throw new Error('Unsupported Airway global initializer.');
                uint(); // i32.const immediate (sign is irrelevant to the state inventory)
                if (bytes[offset++] !== 0x0b) throw new Error('Unsupported Airway global initializer expression.');
                if (mutable) mutableGlobals.push(index);
            }
        } else if (section === 7) {
            const count = uint();
            for (let i = 0; i < count; i++) {
                const key = name(), kind = bytes[offset++], index = uint();
                if (kind === 3) globalExports.set(key, index);
            }
        }
        offset = end;
    }
    if (!memoryBytes || mutableGlobals.length !== 1 || globalExports.get('__stack_pointer') !== mutableGlobals[0]) throw new Error('Airway must expose its sole mutable global, __stack_pointer.');
    return { memoryBytes, mutableGlobals: ['__stack_pointer'] };
}

export async function airwayInputs(root = AIRWAY_ROOT) {
    const files = ['scripts/airway-assets.mjs', 'scripts/build-airway.mjs'];
    async function visit(relative) {
        for (const entry of await readdir(join(root, relative), { withFileTypes: true })) {
            if (entry.name === 'target' || entry.name === '.DS_Store') continue;
            const path = `${relative}/${entry.name}`;
            if (entry.isDirectory()) await visit(path);
            else files.push(path);
        }
    }
    await visit('wasm/airway');
    const lock = JSON.parse(await readFile(join(root, 'wasm/airway/source-lock.json'), 'utf8'));
    if (lock.commit !== AIRWAY_COMMIT || lock.repository !== 'https://github.com/jamesondh/chimera-vocal-synth') throw new Error('Airway upstream source pin mismatch.');
    const vendorFiles = files.filter(path => path.startsWith('wasm/airway/vendor/chimera/'));
    if (lock.files.length !== vendorFiles.length) throw new Error('Airway vendored source inventory mismatch.');
    for (const entry of lock.files) {
        const path = `wasm/airway/vendor/chimera/${entry.path}`;
        if (!vendorFiles.includes(path) || sha256(await readFile(join(root, path))) !== entry.vendoredSha256) throw new Error(`Airway vendored source checksum mismatch: ${entry.path}`);
        if (entry.upstreamSha256 !== entry.vendoredSha256 && !Object.hasOwn(lock.changes, entry.path)) throw new Error(`Undocumented Airway upstream change: ${entry.path}`);
    }
    const inputs = await Promise.all(files.sort().map(async path => ({ path, sha256: sha256(await readFile(join(root, path))) })));
    return { inputs, version: sha256(JSON.stringify(inputs)) };
}

export function airwayManifest(version, moduleFile) {
    return `// Generated by npm run build:airway.\nexport { AIRWAY_WASM_BASE64 } from './${moduleFile}';\nexport const AIRWAY_SOURCE_VERSION = '${version}';\n`;
}

/** No Rust or network required by normal app builds. */
export async function validateAirwayAssets({ root = AIRWAY_ROOT } = {}) {
    const assets = join(root, AIRWAY_ASSETS);
    let manifest;
    try { manifest = JSON.parse(await readFile(join(assets, 'artifact-manifest.json'), 'utf8')); }
    catch { throw new Error('Missing Airway assets. Run npm run build:airway and commit generated files.'); }
    const source = await airwayInputs(root);
    if (manifest.schemaVersion !== 1 || manifest.upstreamCommit !== AIRWAY_COMMIT || manifest.version !== source.version || JSON.stringify(manifest.inputs) !== JSON.stringify(source.inputs)) throw new Error('Stale Airway assets. Run npm run build:airway.');
    if (!/^airway-[a-f0-9]{64}\.wasm$/.test(manifest.wasmFile) || !/^airway-[a-f0-9]{64}\.js$/.test(manifest.moduleFile)) throw new Error('Invalid Airway artifact names.');
    const expected = new Set(['LICENSES.txt', manifest.wasmFile, manifest.moduleFile]);
    if (manifest.files.length !== expected.size || manifest.files.some(file => !expected.delete(file.name)) || expected.size) throw new Error('Invalid Airway artifact inventory.');
    for (const file of manifest.files) {
        const content = await readFile(join(assets, file.name));
        if (content.byteLength !== file.bytes || sha256(content) !== file.sha256 || (file.name !== 'LICENSES.txt' && !file.name.includes(file.sha256))) throw new Error(`Airway artifact checksum mismatch: ${file.name}`);
    }
    const wasm = await readFile(join(assets, manifest.wasmFile));
    const module = new WebAssembly.Module(wasm);
    inspectAirwayAbi(wasm);
    if (WebAssembly.Module.imports(module).length) throw new Error('Airway must not import host functions or memory.');
    const exports = WebAssembly.Module.exports(module);
    for (const name of ['airway_create', 'airway_create_female', 'airway_render', 'airway_set_voice', 'airway_set_vocal', 'airway_set_phoneme', 'airway_set_vocal_controls', 'airway_configure_beat', 'airway_set_beat', 'airway_retarget_hum', 'airway_remaining_samples', 'airway_allocations', '__stack_pointer', 'memory']) {
        if (!exports.some(item => item.name === name)) throw new Error(`Airway ABI is missing ${name}.`);
    }
    const embedded = await readFile(join(assets, manifest.moduleFile), 'utf8');
    if (!embedded.includes(`'${wasm.toString('base64')}'`)) throw new Error('Airway embedded bytes differ from the binary.');
    if (await readFile(join(assets, 'manifest.js'), 'utf8') !== airwayManifest(source.version, manifest.moduleFile)) throw new Error('Airway loader manifest mismatch.');
    return manifest;
}
